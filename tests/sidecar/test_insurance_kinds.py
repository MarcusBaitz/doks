"""Tests for the three insurance kinds on the synthetic corpus.

The corpus is generated by ``corpus/insurance.py``; the comparison with its
ground truth lives in ``bench/insurance_kinds.py`` so the measurement protocol
and these tests cannot disagree about what counts as right.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest
from test_document_kinds import document

from substrakt import document_kinds
from substrakt.extraction.fields import extract
from substrakt.model import ImageRect, PdfRect
from substrakt.parsers import ocr

ROOT = Path(__file__).resolve().parents[2]

_spec = importlib.util.spec_from_file_location("insurance_kinds", ROOT / "bench" / "insurance_kinds.py")
bench = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = bench  # dataclasses look their module up by name
_spec.loader.exec_module(bench)

KINDS = ("policy", "contract_change", "premium_invoice")
SHARED = ("insurer", "policy_number", "policyholder", "line_of_business")
DATES_AND_AMOUNTS = {
    "policy": ("start_date", "end_date", "issue_date", "premium", "annual_premium", "net_premium"),
    "contract_change": ("change_date", "start_date", "end_date", "issue_date", "premium", "net_premium"),
    "premium_invoice": ("invoice_date", "period_start", "period_end", "due_date",
                        "net_premium", "insurance_tax", "premium"),
}
RIGHT = (bench.CORRECT, bench.REVIEW_CORRECT)


@pytest.fixture(scope="module")
def text_layer():
    return bench.evaluate([e for e in bench.truth() if not e.get("scan")])


@pytest.fixture(scope="module")
def scans():
    if not ocr.available():
        pytest.skip("Tesseract or models/tessdata/deu.traineddata is missing")
    return bench.evaluate([e for e in bench.truth() if e.get("scan")])


def test_the_corpus_has_at_least_twenty_documents_per_kind_with_scans_and_truth() -> None:
    entries = bench.truth()
    for kind in KINDS:
        documents = [e for e in entries if e["kind"] == kind]
        assert len(documents) >= 20
        assert sum(e["scan"] for e in documents) >= 5
        assert all((bench.CORPUS / e["file"]).is_file() and e["values"] for e in documents)
        assert {e["set"] for e in documents} == {"tuning", "held_out"}


@pytest.mark.parametrize("kind", KINDS)
def test_each_kind_reads_its_values_from_text_layer_documents(text_layer, kind: str) -> None:
    _, values = text_layer
    for field in (*SHARED, *DATES_AND_AMOUNTS[kind]):
        outcomes = [v.outcome for v in values if v.kind == kind and v.field == field and v.set == "tuning"]
        assert any(o in RIGHT for o in outcomes), f"{kind}.{field} is never read: {outcomes}"

    tuning = [v for v in values if v.kind == kind and v.set == "tuning" and v.outcome != bench.ABSENT]
    share = sum(v.outcome in RIGHT for v in tuning) / len(tuning)
    assert share >= 0.9, f"{kind}: only {share:.0%} of the printed values are read on the tuning layouts"


def test_no_wrong_value_is_delivered_without_a_review_flag(text_layer) -> None:
    kinds, values = text_layer
    assert [v for v in values if v.outcome == bench.WRONG] == []
    assert [k for k in kinds if k.recognised not in (None, k.expected)] == []


def test_every_delivered_value_has_a_location_in_document_coordinates(text_layer) -> None:
    _, values = text_layer
    delivered = [v for v in values if v.outcome == bench.CORRECT]
    assert delivered and all(v.located for v in delivered)


def test_scans_deliver_no_wrong_value_and_no_wrong_kind(scans) -> None:
    kinds, values = scans
    assert len(kinds) == 30
    assert [v for v in values if v.outcome == bench.WRONG] == []
    assert [k for k in kinds if k.recognised not in (None, k.expected)] == []
    assert all(v.located for v in values if v.outcome == bench.CORRECT)
    # Scans must actually be read, not silently yield empty pages.
    assert sum(k.recognised == k.expected for k in kinds) >= 24


def test_a_value_marked_for_review_is_not_grounded() -> None:
    # The insurer from the letterhead is a guess a person confirms.
    kind = document_kinds.load("policy")
    doc = document([(20, [(20, "Nordlicht Versicherung AG")]), (60, [(20, "Herrn")]), (74, [(20, "Jonas Brandt")])])
    result = extract(doc, kind.fields, kind=kind).results[0]
    assert (result.value, result.grounded) == ("Nordlicht Versicherung AG", False)
    assert isinstance(result.locator, (ImageRect, PdfRect))


# --- Core rules the kinds rely on --------------------------------------------


def read(kind_name: str, field: str, rows) -> tuple[str | None, object, bool]:
    kind = document_kinds.load(kind_name)
    spec = next(f for f in kind.fields if f.name == field)
    result = extract(document(rows), [spec], kind=kind).results[0]
    return result.value, result.normalized, result.grounded


def test_a_term_is_read_in_its_printed_spelling_and_normalised() -> None:
    assert read("policy", "payment_mode", [(20, [(20, "Zahlweise: 1/2")])]) == ("1/2", "halbjährlich", True)
    assert read("policy", "payment_mode", [(20, [(20, "Zahlweise: wöchentlich")])])[0] is None


def test_the_line_of_business_is_found_in_a_heading_without_a_label() -> None:
    rows = [(20, [(20, "Versicherungsschein zur Hausrat-Versicherung")])]
    assert read("policy", "line_of_business", rows)[1] == "Hausrat"


def test_two_different_lines_of_business_are_not_decided() -> None:
    rows = [(20, [(20, "Hausratversicherung")]), (40, [(20, "Glasversicherung")])]
    assert read("policy", "line_of_business", rows)[0] is None


def test_the_second_date_after_one_label_is_the_end_of_the_period() -> None:
    rows = [(20, [(20, "Zeitraum vom 01.01.2026 bis 31.12.2026")])]
    assert read("premium_invoice", "period_start", rows)[1] == "2026-01-01"
    assert read("premium_invoice", "period_end", rows)[1] == "2026-12-31"
    # One date is no period: the end stays open instead of repeating the start.
    assert read("premium_invoice", "period_end", [(20, [(20, "Zeitraum 01.01.2026")])])[0] is None


def test_a_policyholder_is_not_read_from_a_sentence() -> None:
    sentence = [(20, [(20, "Versicherungsnehmer hat Änderungen unverzüglich anzuzeigen.")])]
    assert read("policy", "policyholder", sentence)[0] is None
    inside = [(20, [(20, "Der Versicherungsnehmer Jonas Brandt haftet.")])]
    assert read("policy", "policyholder", inside)[0] is None
    assert read("policy", "policyholder", [(20, [(20, "Versicherungsnehmer: Jonas Brandt")])])[0] == "Jonas Brandt"


def test_a_free_text_value_ends_at_the_gap_to_the_next_cell() -> None:
    rows = [(20, [(20, "Versicherungsnehmer"), (300, "Sparte")]),
            (36, [(20, "Tischlerei Okafor"), (300, "Hausratversicherung")])]
    assert read("policy", "policyholder", rows)[0] == "Tischlerei Okafor"


def test_a_column_heading_beside_the_label_is_not_read_as_the_value() -> None:
    # “Kundenkonto” is no label the kind knows; it could be the value in a
    # row layout or the next column heading. Free text cannot tell.
    rows = [(20, [(20, "Versicherungsnehmer"), (300, "Kundenkonto")]),
            (36, [(20, "Tischlerei Okafor"), (300, "4711 Musterhafen")])]
    assert read("policy", "policyholder", rows)[0] is None
    # Without a row below, the word beside the label is the value.
    assert read("policy", "policyholder", [(20, [(20, "Versicherungsnehmer"), (300, "Tischlerei Okafor")])])[0] == "Tischlerei Okafor"


def test_a_number_printed_in_digit_groups_is_not_truncated() -> None:
    assert read("policy", "policy_number", [(20, [(20, "Versicherungsschein-Nr.: 47 110 815")])])[0] is None
    assert read("policy", "policy_number", [(20, [(20, "Versicherungsschein-Nr.: 47110815")])])[0] == "47110815"


def test_the_premium_is_not_read_as_insurance_tax() -> None:
    rows = [(20, [(20, "Beitrag inkl. Versicherungsteuer 186,40 EUR")])]
    assert read("premium_invoice", "insurance_tax", rows)[0] is None
    assert read("premium_invoice", "premium", rows)[1] == 186.4
    assert read("premium_invoice", "insurance_tax", [(20, [(20, "Versicherungsteuer 19 % 29,76 EUR")])])[1] == 29.76


def test_the_annual_premium_and_the_premium_per_payment_period_are_two_values() -> None:
    rows = [(20, [(20, "Jahresbeitrag 372,80 EUR")]), (40, [(20, "Beitrag gemäß Zahlweise 186,40 EUR")])]
    assert read("policy", "annual_premium", rows)[1] == 372.8
    assert read("policy", "premium", rows)[1] == 186.4
    # A document that prints only the annual figure delivers no premium per period.
    assert read("policy", "premium", rows[:1])[0] is None
    assert read("contract_change", "annual_premium", rows[:1])[1] == 372.8


def test_two_different_premiums_under_labels_that_do_not_say_which_are_left_to_the_clerk() -> None:
    rows = [(20, [(20, "Gesamtbeitrag 372,80 EUR")]), (40, [(20, "Beitrag gemäß Zahlweise 186,40 EUR")])]
    value, _, grounded = read("policy", "premium", rows)
    assert value is None and grounded is False
